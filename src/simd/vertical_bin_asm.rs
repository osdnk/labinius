/// Transpose + NTT of `32 * out.len()` polynomials into a materialised `Batch32` array.
/// The 340 MB of output for 2^18 polynomials does not fit any cache, so the last level streams.
pub fn ntt_bin_polys<const Q: u16>(polys: &[BinaryPoly], out: &mut [Batch32]) {
    assert_eq!(polys.len(), 32 * out.len());
    let mut idx = BinaryIndex32::zero();
    unsafe {
        for (b, o) in out.iter_mut().enumerate() {
            let chunk: &[BinaryPoly; 32] =
                &*(polys.as_ptr().add(32 * b) as *const [BinaryPoly; 32]);
            transpose::slice_polys_idx_into(chunk, &mut idx);
            ntt_bin_batch32_nt::<Q>(&idx, o);
        }
        _mm_sfence();
    }
}

/// Transpose + NTT, handing each finished batch to `f` instead of materialising it.
pub fn ntt_bin_stream<const Q: u16>(polys: &[BinaryPoly], mut f: impl FnMut(usize, &Batch32)) {
    assert_eq!(polys.len() % 32, 0);
    let mut buf = Batch32::zero(Representation::Ntt);
    let mut idx = BinaryIndex32::zero();
    unsafe {
        for b in 0..polys.len() / 32 {
            let chunk: &[BinaryPoly; 32] =
                &*(polys.as_ptr().add(32 * b) as *const [BinaryPoly; 32]);
            transpose::slice_polys_idx_into(chunk, &mut idx);
            ntt_bin_batch32::<Q>(&idx, &mut buf);
            f(b, &buf);
        }
    }
}
